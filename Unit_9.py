# Operadores de comparación en Python
# Comparison operators in Python

# Igualdad
# Equality
a = 5
b = 5
print(a == b)  # True

# Desigualdad
# Inequality
a = 5
b = 3
print(a != b)  # True

# Mayor que
# Greater than
a = 7
b = 4
print(a > b)  # True

# Menor que
# Less than
a = 2
b = 6
print(a < b)  # True

# Mayor o igual que
# Greater than or equal to
a = 5
b = 5
print(a >= b)  # True   

# Menor o igual que
# Less than or equal to
a = 3
b = 8
print(a <= b)  # True

# Estos son los operadores de comparación más comunes en Python
# These are the most common comparison operators in Python