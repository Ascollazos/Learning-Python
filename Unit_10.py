# Ejerciocio de identificacion de un numero par o impar
# Exercise to identify an even or odd number

numero = int(input("Por favor ingrese un numero entero: "))

if numero % 2 == 0:
    print("El numero", numero, "es un numero par")
else:
    print("El numero", numero, "es un numero impar")
