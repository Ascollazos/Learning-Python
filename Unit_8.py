# Operadores de asignación en Python
# Assignment operators in Python

# Asignación simple
# Simple assignment

a = 10
print(a)

# Asignación con suma
# Assignment with addition

a += 5  # Equivalente a a = a + 5
print(a)

# Asignación con resta
# Assignment with subtraction  

a -= 3  # Equivalente a a = a - 3
print(a)

# Asignación con multiplicación
# Assignment with multiplication

a *= 2  # Equivalente a a = a * 2
print(a)

# Asignación con división
# Assignment with division

a /= 4  # Equivalente a a = a / 4
print(a)

# Asignación con división entera
# Assignment with integer division

a //= 2  # Equivalente a a = a // 2
print(a)

# Asignación con exponenciación
# Assignment with exponentiation

a **= 3  # Equivalente a a = a ** 3
print(a)

# Asignación con módulo
# Assignment with modulus

a %= 7  # Equivalente a a = a % 7
print(a)

# Estos son los operadores de asignación más comunes en Python
# These are the most common assignment operators in Python