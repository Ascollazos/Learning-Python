# Operadores aritméticos en Python
# Arithmetic operators in Python

# Adición
# Addition
Num_sum_1 = 2
Num_sum_2 = 2   
sum_result = Num_sum_1 + Num_sum_2
print(sum_result)

# Sustracción
# Subtraction
Num_rest_1 = 2.5
Num_rest_2 = 1
rest_result = Num_rest_1 - Num_rest_2
print(rest_result)

# Multiplicación
# Multiplication
Num_mult_1 = 2
Num_mult_2 = 3.14
mult_result = Num_mult_1 * Num_mult_2
print(mult_result)

# División
# Division
Num_Div_1 = 10 
Num_Div_2 = 2
div_result = Num_Div_1 / Num_Div_2
print(div_result)

# División de enteros
# Integer Division
Num_intdiv_1 = 10
Num_intdiv_2 = 3
intdiv_result = Num_intdiv_1 // Num_intdiv_2
print(intdiv_result)

# Exponenciación
# Exponentiation
Num_exp_1 = 2
Num_exp_2 = 3
exp_result = Num_exp_1 ** Num_exp_2
print(exp_result)

# Módulo
# Modulus
Num_mod_1 = 10
Num_mod_2 = 3
mod_result = Num_mod_1 % Num_mod_2
print(mod_result)

